#!/usr/bin/env node
// ---------------------------------------------------------------------------
// One-time script: reads card assets from public/generation/card/ and outputs
// src/lib/member-card/asset-data.ts with base64-embedded constants.
// ---------------------------------------------------------------------------

import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const ASSETS_DIR = resolve(ROOT, "public/generation/card");
const OUT_FILE = resolve(ROOT, "src/lib/member-card/asset-data.ts");

function toBase64(filePath) {
  return readFileSync(filePath).toString("base64");
}

const fontBelleza = toBase64(resolve(ASSETS_DIR, "font_belleza.ttf"));
const fontIntroBlackAlt = toBase64(resolve(ASSETS_DIR, "font_intro-black-alt.ttf"));

const output = `// ---------------------------------------------------------------------------
// Member card — Embedded asset data (auto-generated by scripts/generate-card-assets.mjs)
// Do not edit manually. Re-run the script to regenerate.
// ---------------------------------------------------------------------------

export const FONT_BELLEZA_BASE64 = "${fontBelleza}";

export const FONT_INTRO_BLACK_ALT_BASE64 = "${fontIntroBlackAlt}";
`;

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(OUT_FILE, output, "utf-8");

const sizeKB = (readFileSync(OUT_FILE).length / 1024).toFixed(1);
console.log(`Generated ${OUT_FILE} (${sizeKB} KB)`);
